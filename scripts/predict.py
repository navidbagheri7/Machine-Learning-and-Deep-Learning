"""Batch inference from a locally trained Adult artifact and a feature CSV."""

import argparse

import joblib
import numpy as np
import pandas as pd

from learning_lab.data import CATEGORICAL, NUMERIC
from learning_lab.uncertainty import binary_temperature


def predict(artifact, frame):
    required = artifact["features"]
    missing = sorted(set(required) - set(frame.columns))
    if missing:
        raise ValueError(f"Missing required features: {missing}")
    frame = frame[required].copy()
    for name in NUMERIC:
        frame[name] = pd.to_numeric(frame[name], errors="raise")
        if np.isinf(frame[name].to_numpy(dtype=float)).any():
            raise ValueError(f"Infinite values in {name}")
    for name in CATEGORICAL:
        frame[name] = frame[name].map(lambda x: x.strip() if isinstance(x, str) else x)
    raw = artifact["pipeline"].predict_proba(frame)[:, 1]
    calibrated = binary_temperature(raw, artifact["temperature"])
    return pd.DataFrame(
        {
            "probability_income_above_50k": calibrated,
            "decision": (calibrated >= artifact["threshold"]).astype(int),
        }
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifact", required=True)
    parser.add_argument("--input", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    # Load only artifacts generated by this repository or another trusted source.
    bundle = joblib.load(args.artifact)
    frame = pd.read_csv(args.input, na_values="?")
    predict(bundle, frame).to_csv(args.output, index=False)


if __name__ == "__main__":
    main()
